const dicts: Record<Lang, Record<I18nKey, string>> = { en, ar };

export function makeT(lang: Lang): TFn {
  const dict = dicts[lang];
  return (key, vars) => {
    let s = dict[key] ?? en[key] ?? key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        s = s.replaceAll(`{${k}}`, String(v));
      }
    }
    return s;
  };
}
